import type { CodeCatalog, Manifest, TriggerSubscription } from '../types.js';

/** A small code catalog for tests. */
export function fakeCatalog(): CodeCatalog {
  return {
    toolIds: () => ['tool:gmail', 'tool:calendar', 'tool:web_search', 'tool:web_fetch', 'tool:mission_registry'],
    triggerIds: () => ['trigger:chat', 'trigger:cron', 'trigger:email.received'],
    actionIds: () => [
      'action:email.send',
      'action:email.archive',
      'action:email.delete',
      'action:registry.create',
      'action:registry.edit',
      'action:registry.freeze',
      'action:registry.delete',
    ],
    toolReservedFor: (id) => (id === 'tool:mission_registry' ? ['sys-mission-admin'] : undefined),
    validateTriggerParams: (sub: TriggerSubscription) => {
      const { use, ...params } = sub;
      if (use === 'trigger:cron') {
        if (typeof params.at !== 'string') return 'needs "at", a cron expression such as "0 7 * * *".';
        const extra = Object.keys(params).filter((k) => k !== 'at');
        return extra.length > 0 ? `has unknown parameters: ${extra.join(', ')}.` : null;
      }
      const keys = Object.keys(params);
      return keys.length > 0 ? `takes no parameters, but has ${keys.join(', ')}.` : null;
    },
  };
}

/** The example of §A.4. */
export const EXAMPLE_YAML = `id: m_k7q3zp2xw9ha                     # generated by the harness at creation, never changes
name: inbox-curator                    # shown to the user; unique
description: Sorts my inbox and drafts replies to mail that needs one   # one line, read by triage (§B.3)
version: 3                             # increases on every edit, logged with each run
status: active

triggers:
  - use: trigger:cron                  # a schedule is a trigger that fires on a timer
    at: "0 7 * * *"                    # every morning at 07:00
  - use: trigger:email.received
  - use: trigger:chat                  # I can talk to this mission in the chat (§B.3)

tools:
  - tool:gmail
  - tool:calendar

context:                               # what the model reads from this manifest on every run (§C.1)
  instructions: |                      # free text, the model reads this verbatim
    You are my inbox curator. Your mission is to filter out the noise
    and make sure only mail that deserves my attention reaches me.

signals:                               # user actions that the harness records for the mission (§A.4.7)
  - signal:message.rated               # a good and a bad button under the curator's answers

gates:
  - use: gate:allow                                       # archiving changes my mailbox
    for: action:email.archive
  - use: gate:require_approval
    for: action:email.send
    note: ask before sending any reply
  - use: gate:deny                                        # a ban: the action never runs
    for: action:email.delete

model: claude-haiku-5-5                # optional: a cheap model is enough for sorting mail
effort: low                            # optional: overrides the default effort (§A.1)

limits:                                # optional: lower than the harness defaults, never higher (§D)
  max_steps: 20
  max_cost_usd: 0.50
  max_minutes: 10
`;

export function exampleManifest(overrides: Partial<Manifest> = {}): Manifest {
  return {
    id: 'm_k7q3zp2xw9ha',
    name: 'inbox-curator',
    description: 'Sorts my inbox and drafts replies to mail that needs one',
    version: 3,
    status: 'active',
    triggers: [{ use: 'trigger:cron', at: '0 7 * * *' }, { use: 'trigger:email.received' }, { use: 'trigger:chat' }],
    tools: ['tool:gmail', 'tool:calendar'],
    context: {
      instructions:
        'You are my inbox curator. Your mission is to filter out the noise\nand make sure only mail that deserves my attention reaches me.\n',
    },
    signals: ['signal:message.rated'],
    gates: [
      { use: 'gate:allow', for: 'action:email.archive' },
      { use: 'gate:require_approval', for: 'action:email.send', note: 'ask before sending any reply' },
      { use: 'gate:deny', for: 'action:email.delete' },
    ],
    model: 'claude-haiku-5-5',
    effort: 'low',
    limits: { max_steps: 20, max_cost_usd: 0.5, max_minutes: 10 },
    ...overrides,
  };
}
