describe('qrEncode', () => {
  for (const [link, expected] of Object.entries(REFERENCE)) {
    it(`gives the reference matrix for ${link}`, () => {
      expect(qrEncode(link)).toEqual(expected);
    });
  }

  it('gives the same matrix as the reference when the mask is set', () => {
    const [link, expected] = Object.entries(REFERENCE)[1]!;
    expect(qrEncode(link, { mask: expected.mask }).rows).toEqual(expected.rows);
    expect(qrEncode(link, { mask: (expected.mask + 1) % 8 }).rows).not.toEqual(expected.rows);
  });

  it('chooses the smallest version that fits', () => {
    expect(qrMaxBytes(1)).toBe(14);
    expect(qrMaxBytes(2)).toBe(26);
    expect(qrMaxBytes(6)).toBe(106);
    expect(qrEncode('x'.repeat(14)).version).toBe(1);
    expect(qrEncode('x'.repeat(15)).version).toBe(2);
    expect(qrEncode('x'.repeat(106)).version).toBe(6);
    expect(qrEncode('x'.repeat(107)).version).toBe(7);
    const v7 = qrEncode('x'.repeat(107));
    expect(v7.rows).toHaveLength(45);
    expect(v7.rows.every((r) => r.length === 45 && /^[01]+$/.test(r))).toBe(true);
  });

  it('refuses a text that is too long, and a text that is not printable ASCII', () => {
    expect(qrEncode('x'.repeat(qrMaxBytes(10))).version).toBe(10);
    expect(() => qrEncode('x'.repeat(qrMaxBytes(10) + 1))).toThrow('The text is too long for a QR code here: 214 characters, and at most 213 fit.');
    expect(() => qrEncode('https://t.me/ada_bot?start=48291é')).toThrow('printable ASCII');
    expect(() => qrEncode('a\nb')).toThrow('printable ASCII');
  });

  it('refuses a mask outside 0 to 7', () => {
    expect(() => qrEncode('abc', { mask: 8 })).toThrow('The mask is a whole number from 0 to 7.');
  });
});
